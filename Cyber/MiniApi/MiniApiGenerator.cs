    [Generator]
    public class MiniApiGenerator : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            // 收集实现 IMiniApiController 接口的类
            var miniApiClasses = context.SyntaxProvider
                .CreateSyntaxProvider(
                    predicate: static (s, _) => MiniApiGenerationStatic.IsClassImplementingMiniApiController(s),
                    transform: static (ctx, _) => MiniApiGenerationStatic.GetMiniApiClassInfo(ctx))
                .Where(static m => m is not null);

            // 生成端点映射 + 响应DTO
            context.RegisterImplementationSourceOutput(
                miniApiClasses.Collect(),
                static (spc, classes) =>
                {
                    var (handlersSource, mapSource) = GenerateEndpointMappings(classes);

                    spc.AddSource("MiniApiEndpointExtensions.g.cs", SourceText.From(handlersSource, Encoding.UTF8));
                    spc.AddSource("MapCyberMiniApis.g.cs", SourceText.From(mapSource, Encoding.UTF8));

                    var modelSource = GenerateResponseModels(classes);
                    spc.AddSource("MiniApiResponseModel.g.cs", SourceText.From(modelSource, Encoding.UTF8));
                });
        }

        #region 路由冲突检测

        private static Dictionary<string, List<string>> CheckRouteConflicts(ImmutableArray<MiniApiClassInfo?> classes)
        {
            var conflicts = new Dictionary<string, List<string>>();
            var endpointMethods = new Dictionary<string, List<string>>();

            foreach (var classInfo in classes)
            {
                if (classInfo == null) continue;

                foreach (var method in classInfo.Methods)
                {
                    var route = method.RouteTemplate ?? method.MethodName;
                    var key = $"{method.HttpMethod} {classInfo.RoutePrefix}/{route}";

                    if (!endpointMethods.ContainsKey(key))
                    {
                        endpointMethods[key] = new List<string>();
                    }
                    endpointMethods[key].Add($"{classInfo.ClassName}.{method.MethodName}({string.Join(", ", method.Parameters.Select(p => p.Type))})");
                }
            }

            // 找出重复的端点
            foreach (var kvp in endpointMethods)
            {
                if (kvp.Value.Count > 1)
                {
                    conflicts[kvp.Key] = kvp.Value;
                }
            }

            return conflicts;
        }

        #endregion

        #region 生成端点映射代码

        private static (string HandlersSource, string MapSource) GenerateEndpointMappings(ImmutableArray<MiniApiClassInfo?> classes)
        {
            // 检查路由冲突
            var routeConflicts = CheckRouteConflicts(classes);
            if (routeConflicts.Count > 0)
            {
                var errorSb = new StringBuilder();
                errorSb.AppendLine("#error MiniAPI 路由冲突：同一个路由和HTTP方法不能有多个重载方法，请修改路由或方法名");
                foreach (var conflict in routeConflicts)
                {
                    errorSb.AppendLine($"#error 冲突端点：{conflict.Key}");
                    foreach (var method in conflict.Value)
                    {
                        errorSb.AppendLine($"#error   - {method}");
                    }
                }
                // 生成一个空的扩展方法类，避免其他生成器引用时出错
                errorSb.AppendLine();
                errorSb.AppendLine("namespace Cyber");
                errorSb.AppendLine("{");
                errorSb.AppendLine("    public static partial class MiniApiEndpointExtensions");
                errorSb.AppendLine("    {");
                errorSb.AppendLine("        public static IEndpointRouteBuilder MapCyberMiniApis(this IEndpointRouteBuilder endpoints)");
                errorSb.AppendLine("        {");
                errorSb.AppendLine("            return endpoints;");
                errorSb.AppendLine("        }");
                errorSb.AppendLine("    }");
                errorSb.AppendLine("}");
                var errorSource = errorSb.ToString();
                return (errorSource, errorSource);
            }

            // 生成 MiniApiEndpointExtensions.g.cs（包含静态 handler 方法）
            var handlersSb = new StringBuilder();
            handlersSb.AppendLine("// <auto-generated/>");
            handlersSb.AppendLine("// This file is auto-generated by Cyber.AOT MiniApiGenerator - Handler Methods");
            handlersSb.AppendLine("#nullable enable");
            handlersSb.AppendLine("using Microsoft.AspNetCore.Builder;");
            handlersSb.AppendLine("using Microsoft.AspNetCore.Http;");
            handlersSb.AppendLine("using Microsoft.AspNetCore.Routing;");
            handlersSb.AppendLine("using Microsoft.AspNetCore.Mvc;");
            handlersSb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
            handlersSb.AppendLine("using Microsoft.Extensions.Options;");
            handlersSb.AppendLine("using System;");
            handlersSb.AppendLine("using System.Collections.Generic;");
            handlersSb.AppendLine("using System.Text.Json;");
            handlersSb.AppendLine("using System.Text.Json.Serialization.Metadata;");
            handlersSb.AppendLine("using System.Threading.Tasks;");
            handlersSb.AppendLine();

            handlersSb.AppendLine("namespace Cyber");
            handlersSb.AppendLine("{");
            handlersSb.AppendLine("    /// <summary>");
            handlersSb.AppendLine("    /// 自动生成的 MiniAPI 端点映射扩展方法 - Handler Methods");
            handlersSb.AppendLine("    /// </summary>");
            handlersSb.AppendLine("    public static partial class MiniApiEndpointExtensions");
            handlersSb.AppendLine("    {");

            // 先生成所有静态 handler 方法（AOT 安全，避免 lambda）
            var validClasses = classes.Where(c => c != null && c.Methods.Count > 0).ToList();
            foreach (var classInfo in validClasses)
            {
                if (classInfo == null) continue;
                foreach (var method in classInfo.Methods)
                {
                    GenerateStaticHandlerMethod(handlersSb, classInfo, method);
                }
            }

            handlersSb.AppendLine("    }");
            handlersSb.AppendLine("}");

            // 生成 MapCyberMiniApis.g.cs（包含 MapCyberMiniApis 方法）
            var mapSb = new StringBuilder();
            mapSb.AppendLine("// <auto-generated/>");
            mapSb.AppendLine("// This file is auto-generated by Cyber.AOT MiniApiGenerator - MapCyberMiniApis Method");
            mapSb.AppendLine("#nullable enable");
            mapSb.AppendLine("using Microsoft.AspNetCore.Builder;");
            mapSb.AppendLine("using Microsoft.AspNetCore.Routing;");
            mapSb.AppendLine();

            mapSb.AppendLine("namespace Cyber");
            mapSb.AppendLine("{");
            mapSb.AppendLine("    /// <summary>");
            mapSb.AppendLine("    /// 自动生成的 MiniAPI 端点映射扩展方法 - MapCyberMiniApis");
            mapSb.AppendLine("    /// </summary>");
            mapSb.AppendLine("    public static partial class MiniApiEndpointExtensions");
            mapSb.AppendLine("    {");
            mapSb.AppendLine("        /// <summary>");
            mapSb.AppendLine("        /// 自动映射所有标记了 [MiniApi] 特性的端点");
            mapSb.AppendLine("        /// </summary>");
            mapSb.AppendLine("        public static IEndpointRouteBuilder MapCyberMiniApis(this IEndpointRouteBuilder app)");
            mapSb.AppendLine("        {");

            foreach (var classInfo in validClasses)
            {
                if (classInfo == null) continue;
                GenerateClassEndpointMappings(mapSb, classInfo);
            }

            mapSb.AppendLine("            return app;");
            mapSb.AppendLine("        }");
            mapSb.AppendLine("    }");
            mapSb.AppendLine("}");

            return (handlersSb.ToString(), mapSb.ToString());
        }

        /// <summary>
        /// 为每个方法生成静态 RequestDelegate（AOT 安全，使用 MapMethods 底层 API）
        /// </summary>
        private static void GenerateStaticHandlerMethod(StringBuilder sb, MiniApiClassInfo classInfo, MiniApiMethodInfo method)
        {
            var handlerMethodName = GetHandlerMethodName(classInfo.ClassName, method.MethodName, method.HttpMethod, method);
            var responseTypeName = MiniApiGenerationStatic.GetResponseTypeName(classInfo.ClassName, method.MethodName, method.HttpMethod, method);
            var fullResponseTypeName = method.NoResultModel
                ? "Cyber.CyberErrorResponse"
                : $"{classInfo.Namespace}.{responseTypeName}";

            // 生成 RequestDelegate 变量（使用 MapMethods 底层 API）
            sb.AppendLine($"        private static readonly Microsoft.AspNetCore.Http.RequestDelegate __{handlerMethodName} = static async (Microsoft.AspNetCore.Http.HttpContext ctx) =>");
            sb.AppendLine("        {");
            sb.AppendLine("            try");
            sb.AppendLine("            {");
            sb.AppendLine("              GetServiceProvider.SetCurrentScope(ctx ,ctx.RequestServices);");

            // JWT 鉴权检测
            bool skipJwt = method.AllowAnonymous;
            if (!skipJwt)
            {
                sb.AppendLine("              if (!await JwtAuthHelper.AuthenticateAsync(ctx))");
                sb.AppendLine("              {");
                sb.AppendLine("                  return;");
                sb.AppendLine("              }");
            }

            // 重复请求拦截
            bool ignoreRepeated = method.HttpMethod == "GET" || method.IgnoreRepeatedRequest || classInfo.IgnoreRepeatedRequest;
            if (!ignoreRepeated)
            {
                sb.AppendLine("              if (await RepeatedRequestHelper.CheckAsync(ctx))");
                sb.AppendLine("              {");
                sb.AppendLine("                  return;");
                sb.AppendLine("              }");
            }

            // 手动解析参数
            foreach (var param in method.Parameters)
            {
                if (param.HasFromRoute)
                {
                    sb.AppendLine($"              var __{param.Name}Str = ctx.Request.RouteValues[\"{param.Name}\"]?.ToString();");
                    sb.AppendLine($"              if (__{param.Name}Str == null)");
                    sb.AppendLine("               {");
                    GenerateErrorResponse(sb, fullResponseTypeName, 400, "Cyber.ResultCode.Exception", $"Missing route parameter: {param.Name}");
                    sb.AppendLine("                  return;");
                    sb.AppendLine("                }");

                    // 根据类型解析
                    var parseExpr = GetParseExpression(param.Type, $"__{param.Name}Str");
                    if (parseExpr != null)
                    {
                        sb.AppendLine($"              {param.Type} {param.Name} = {parseExpr};");
                    }
                    else
                    {
                        // 无法解析的类型，使用 JsonTypeInfos
                        var jsonTypeInfoName = MiniApiGenerationStatic.GetJsonTypeInfoPropertyName(param.Type);
                        sb.AppendLine($"              {param.Type} {param.Name} = System.Text.Json.JsonSerializer.Deserialize<{param.Type}>(__{param.Name}Str, JsonTypeInfos.{jsonTypeInfoName});");
                    }
                }
                else if (param.HasFromQuery)
                {
                    // 简单类型：直接从 query string 取单个值
                    if (param.IsSimpleType)
                    {
                        sb.AppendLine($"              var __{param.Name}Str = ctx.Request.Query[\"{param.Name}\"].FirstOrDefault();");
                        sb.AppendLine($"              if (__{param.Name}Str == null)");
                        sb.AppendLine("               {");
                        GenerateErrorResponse(sb, fullResponseTypeName, 400, "Cyber.ResultCode.Exception", $"Missing query parameter: {param.Name}");
                        sb.AppendLine("                  return;");
                        sb.AppendLine("               }");

                        var parseExpr = GetParseExpression(param.Type, $"__{param.Name}Str");
                        if (parseExpr != null)
                        {
                            sb.AppendLine($"              {param.Type} {param.Name} = {parseExpr};");
                        }
                        else
                        {
                            // 使用 JsonTypeInfos 进行反序列化
                            var jsonTypeInfoName = MiniApiGenerationStatic.GetJsonTypeInfoPropertyName(param.Type);
                            sb.AppendLine($"              {param.Type} {param.Name} = System.Text.Json.JsonSerializer.Deserialize<{param.Type}>(__{param.Name}Str, JsonTypeInfos.{jsonTypeInfoName});");
                        }
                    }
                    else
                    {
                        // 复杂类型：从查询字符串组装实体对象
                        sb.AppendLine($"              {param.Type} {param.Name} = new {param.Type}();");

                        foreach (var prop in param.Properties)
                        {
                            // 数组类型属性：从查询字符串取多个值
                            if (prop.IsArrayType)
                            {
                                sb.AppendLine($"              var __{param.Name}_{prop.Name}Values = ctx.Request.Query[\"{prop.Name}\"].ToArray();");
                                sb.AppendLine($"              if (__{param.Name}_{prop.Name}Values.Length > 0)");
                                sb.AppendLine("               {");

                                // 简单元素类型：逐个解析
                                var elementParseExpr = GetParseExpression(prop.ElementType, "__val");
                                if (elementParseExpr != null)
                                {
                                    sb.AppendLine($"                  {param.Name}.{prop.Name} = __{param.Name}_{prop.Name}Values.Select(__val => {elementParseExpr.Replace("__val", "__val")}).ToList();");
                                }
                                else
                                {
                                    // 复杂元素类型：使用 JsonTypeInfos 反序列化每个元素
                                    var elementJsonTypeInfoName = MiniApiGenerationStatic.GetJsonTypeInfoPropertyName(prop.ElementType);
                                    sb.AppendLine($"                  {param.Name}.{prop.Name} = __{param.Name}_{prop.Name}Values.Select(__val => System.Text.Json.JsonSerializer.Deserialize<{prop.ElementType}>(__val, JsonTypeInfos.{elementJsonTypeInfoName})).ToList();");
                                }
                                sb.AppendLine("               }");
                            }
                            else
                            {
                                // 简单类型属性：直接解析
                                sb.AppendLine($"              var __{param.Name}_{prop.Name}Str = ctx.Request.Query[\"{prop.Name}\"].FirstOrDefault();");

                                var parseExpr = GetParseExpression(prop.Type, $"__{param.Name}_{prop.Name}Str");
                                if (parseExpr != null)
                                {
                                    sb.AppendLine($"              if (__{param.Name}_{prop.Name}Str != null)");
                                    sb.AppendLine("               {");
                                    sb.AppendLine($"                  {param.Name}.{prop.Name} = {parseExpr};");
                                    sb.AppendLine("               }");
                                }
                                else
                                {
                                    // 复杂属性类型，使用 JsonTypeInfos 反序列化
                                    var propJsonTypeInfoName = MiniApiGenerationStatic.GetJsonTypeInfoPropertyName(prop.Type);
                                    sb.AppendLine($"              if (__{param.Name}_{prop.Name}Str != null)");
                                    sb.AppendLine("               {");
                                    sb.AppendLine($"                  {param.Name}.{prop.Name} = System.Text.Json.JsonSerializer.Deserialize<{prop.Type}>(__{param.Name}_{prop.Name}Str, JsonTypeInfos.{propJsonTypeInfoName});");
                                    sb.AppendLine("               }");
                                }
                            }
                        }

                        // 如果存在对应的 Validator，进行模型验证
                        if (param.HasValidator)
                        {
                            sb.AppendLine($"              var __{param.Name}Validator = ctx.RequestServices.GetRequiredService<FluentValidation.AbstractValidator<{param.Type}>>();");
                            sb.AppendLine($"              var __{param.Name}ValidationResult = __{param.Name}Validator.Validate({param.Name});");
                            sb.AppendLine($"              if (!await Cyber.MiniApiExceptionHelper.HandleValidationResultAsync(ctx, __{param.Name}ValidationResult))");
                            sb.AppendLine("               {");
                            sb.AppendLine("                  return;");
                            sb.AppendLine("               }");
                        }
                    }
                }
                else if (param.HasFromBody)
                {
                    // 简单类型：直接读取字符串并转换
                    if (IsSimpleTypeString(param.Type))
                    {
                        sb.AppendLine($"              string __{param.Name}Json = await new System.IO.StreamReader(ctx.Request.Body).ReadToEndAsync();");
                        var parseExpr = GetParseExpression(param.Type, $"__{param.Name}Json");
                        if (parseExpr != null)
                        {
                            sb.AppendLine($"              {param.Type} {param.Name} = {parseExpr};");
                        }
                        else
                        {
                            sb.AppendLine($"              {param.Type} {param.Name} = System.Text.Json.JsonSerializer.Deserialize<{param.Type}>(__{param.Name}Json);");
                        }
                    }
                    else
                    {
                        // 复杂类型：使用 MiniApiExceptionHelper.ReadJsonAsync
                        var jsonTypeInfoName = MiniApiGenerationStatic.GetJsonTypeInfoPropertyName(param.Type);
                        var serializationType = MiniApiGenerationStatic.GetJsonSerializationType(param.Type);

                        sb.AppendLine($"              var {param.Name}_tmp = await Cyber.MiniApiExceptionHelper.ReadJsonAsync<{serializationType}>(ctx, JsonTypeInfos.{jsonTypeInfoName}, \"{param.Name}\");");
                        sb.AppendLine($"              if ({param.Name}_tmp == null)");
                        sb.AppendLine("               {");
                        sb.AppendLine("                  return;");
                        sb.AppendLine("               }");

                        // 如果参数类型是 List/IList，需要将 IEnumerable 转换回去
                        if (serializationType != param.Type)
                        {
                            sb.AppendLine($"              {param.Type} {param.Name} = {param.Name}_tmp.ToList();");
                        }
                        else
                        {
                            sb.AppendLine($"              {param.Type} {param.Name} = {param.Name}_tmp;");
                        }

                        // 如果存在对应的 Validator，进行模型验证
                        if (param.HasValidator)
                        {
                            sb.AppendLine($"              var __{param.Name}Validator = ctx.RequestServices.GetRequiredService<FluentValidation.AbstractValidator<{param.Type}>>();");
                            sb.AppendLine($"              var __{param.Name}ValidationResult = __{param.Name}Validator.Validate({param.Name});");
                            sb.AppendLine($"              if (!await Cyber.MiniApiExceptionHelper.HandleValidationResultAsync(ctx, __{param.Name}ValidationResult))");
                            sb.AppendLine("               {");
                            sb.AppendLine("                  return;");
                            sb.AppendLine("               }");
                        }
                    }
                }
                else if (param.HasFromForm)
                {
                    // FromForm：简单类型走 form 字段，IFormFile/IFormFileCollection 走 form 文件
                    sb.AppendLine($"              if (!ctx.Request.HasFormContentType)");
                    sb.AppendLine("              {");
                    GenerateErrorResponse(sb, fullResponseTypeName, 400, "Cyber.ResultCode.Exception", $"Missing form content type for parameter: {param.Name}");
                    sb.AppendLine("                  return;");
                    sb.AppendLine("              }");
                    sb.AppendLine($"              var __{param.Name}Form = await ctx.Request.ReadFormAsync();");

                    if (param.IsFileType)
                    {
                        // IFormFileCollection：直接使用 form.Files
                        if (param.Type.Contains("IFormFileCollection"))
                        {
                            sb.AppendLine($"              {param.Type} {param.Name} = __{param.Name}Form.Files;");
                        }
                        else
                        {
                            // IFormFile：按名称取单个文件
                            sb.AppendLine($"              {param.Type}? {param.Name}_tmp = __{param.Name}Form.Files.GetFile(\"{param.Name}\");");
                            sb.AppendLine($"              if ({param.Name}_tmp == null)");
                            sb.AppendLine("               {");
                            GenerateErrorResponse(sb, fullResponseTypeName, 400, "Cyber.ResultCode.Exception", $"Missing form file: {param.Name}");
                            sb.AppendLine("                  return;");
                            sb.AppendLine("               }");
                            sb.AppendLine($"              {param.Type} {param.Name} = {param.Name}_tmp;");
                        }
                    }
                    else
                    {
                        // 简单类型：按名称取 form 字段
                        sb.AppendLine($"              var __{param.Name}Str = __{param.Name}Form[\"{param.Name}\"].FirstOrDefault();");
                        sb.AppendLine($"              if (__{param.Name}Str == null)");
                        sb.AppendLine("               {");
                        GenerateErrorResponse(sb, fullResponseTypeName, 400, "Cyber.ResultCode.Exception", $"Missing form field: {param.Name}");
                        sb.AppendLine("                  return;");
                        sb.AppendLine("               }");

                        var parseExpr = GetParseExpression(param.Type, $"__{param.Name}Str");
                        if (parseExpr != null)
                        {
                            sb.AppendLine($"              {param.Type} {param.Name} = {parseExpr};");
                        }
                        else
                        {
                            // 使用 JsonTypeInfos 进行反序列化
                            var formJsonTypeInfoName = MiniApiGenerationStatic.GetJsonTypeInfoPropertyName(param.Type);
                            sb.AppendLine($"              {param.Type} {param.Name} = System.Text.Json.JsonSerializer.Deserialize<{param.Type}>(__{param.Name}Str, JsonTypeInfos.{formJsonTypeInfoName});");
                        }
                    }
                }
                else
                {
                    sb.AppendLine($"              var {param.Name} = ctx.RequestServices.GetRequiredService<{param.Type}>();");
                }
            }

            // 从 HttpContext.RequestServices 获取 DI 容器中的实例
            sb.AppendLine($"              var __instance = ctx.RequestServices.GetRequiredService<{classInfo.FullClassName}>();");

            // 调用方法
            var callArgs = string.Join(", ", method.Parameters.Select(p => p.Name));
            var callExpr = $"__instance.{method.MethodName}({callArgs})";

            // 处理返回值
            if (method.NoResultModel)
            {
                if (method.IsVoid)
                {
                    sb.AppendLine($"              {AwaitIfAsync(callExpr, method)};");
                    sb.AppendLine("              ctx.Response.StatusCode = 200;");
                }
                else
                {
                    sb.AppendLine($"            var __data = {AwaitIfAsync(callExpr, method)};");
                    // [NoResultModel] 不包 ResponseDTO，直接根据返回类型输出：
                    //   - IFormFile / IFormFileCollection -> 文件下载流
                    //   - string                         -> text/plain; charset=utf-8
                    //   - 其它（含实体）                 -> JSON 序列化
                    GenerateRawResponseSerialization(sb, method.ActualReturnType, "__data");
                }
            }
            else
            {
                if (method.IsVoid)
                {
                    sb.AppendLine($"              {AwaitIfAsync(callExpr, method)};");
                    sb.AppendLine($"              var __response = new {fullResponseTypeName} {{ Code = Cyber.ResultCode.Success, Timestamp = DateTimeOffset.UtcNow.ToUnixTimeSeconds() }};");
                }
                else
                {
                    sb.AppendLine($"              var __data = {AwaitIfAsync(callExpr, method)};");
                    sb.AppendLine($"              var __response = new {fullResponseTypeName} {{ Code = Cyber.ResultCode.Success, Data = __data, Timestamp = DateTimeOffset.UtcNow.ToUnixTimeSeconds() }};");
                }

                // AOT 安全序列化输出
                GenerateSuccessResponseSerialization(sb, responseTypeName, "__response");
            }

            sb.AppendLine("            }");
            // 添加全局异常处理
            GenerateGlobalExceptionHandlers(sb, fullResponseTypeName, method);

            sb.AppendLine("            finally");
            sb.AppendLine("            {");
            sb.AppendLine("                 RepeatedRequestHelper.ClearRequestFlag(ctx);");
            sb.AppendLine("                 GetServiceProvider.ClearCurrentScope();");
            sb.AppendLine("            }");

            sb.AppendLine("        };");
            sb.AppendLine();
        }

        /// <summary>
        /// 生成全局异常处理器
        /// </summary>
        private static void GenerateGlobalExceptionHandlers(StringBuilder sb, string fullResponseTypeName, MiniApiMethodInfo method)
        {
            // catch NeedLoginException：HTTP 401，JSON Code=500（使用 ResultCode.Exception）
            sb.AppendLine("            catch (Cyber.NeedLoginException ex)");
            sb.AppendLine("            {");
            sb.AppendLine("                await Cyber.MiniApiExceptionHelper.HandleNeedLoginExceptionAsync(ctx, ex);");
            sb.AppendLine("            }");

            // catch OutPutException：HTTP 500，JSON Code=450（使用 ResultCode.ParameterError）
            sb.AppendLine("            catch (Cyber.OutPutException ex)");
            sb.AppendLine("            {");
            sb.AppendLine("                await Cyber.MiniApiExceptionHelper.HandleOutPutExceptionAsync(ctx, ex);");
            sb.AppendLine("            }");

            sb.AppendLine("            catch (Exception ex)");
            sb.AppendLine("            {");
            sb.AppendLine("                await Cyber.MiniApiExceptionHelper.HandleGenericExceptionAsync(ctx, ex);");
            sb.AppendLine("            }");
        }

        /// <summary>
        /// 获取类型的解析表达式
        /// </summary>
        private static string? GetParseExpression(string type, string sourceExpr)
        {
            // 基础类型映射（使用 UtilConvert）
            var simpleTypes = new Dictionary<string, string>
            {
                // 基础类型
                ["int"] = $"{sourceExpr}.ObjToInt()",
                ["global::System.Int32"] = $"{sourceExpr}.ObjToInt()",
                ["long"] = $"{sourceExpr}.ObjToLong()",
                ["global::System.Int64"] = $"{sourceExpr}.ObjToLong()",
                ["float"] = $"{sourceExpr}.ObjToDouble().ToSingle()", // UtilConvert 没有 float 专用方法，用 double 转
                ["global::System.Single"] = $"{sourceExpr}.ObjToDouble().ToSingle()",
                ["double"] = $"{sourceExpr}.ObjToDouble()",
                ["global::System.Double"] = $"{sourceExpr}.ObjToDouble()",
                ["decimal"] = $"{sourceExpr}.ObjToDecimal()",
                ["global::System.Decimal"] = $"{sourceExpr}.ObjToDecimal()",
                ["bool"] = $"bool.Parse({sourceExpr})", // UtilConvert 没有 bool 专用方法
                ["global::System.Boolean"] = $"bool.Parse({sourceExpr})",
                ["string"] = sourceExpr,
                ["global::System.String"] = sourceExpr,
                ["Guid"] = $"Guid.Parse({sourceExpr})",
                ["global::System.Guid"] = $"Guid.Parse({sourceExpr})",
                // DateTime 类型（使用 UtilConvert）
                ["DateTime"] = $"{sourceExpr}.ObjToDate()",
                ["global::System.DateTime"] = $"{sourceExpr}.ObjToDate()",
                ["DateTimeOffset"] = $"DateTimeOffset.Parse({sourceExpr})",
                ["global::System.DateTimeOffset"] = $"DateTimeOffset.Parse({sourceExpr})",

                // 可空类型（使用 UtilConvert 的 Null 版本）
                ["int?"] = $"{sourceExpr}.ObjToIntNull()",
                ["global::System.Int32?"] = $"{sourceExpr}.ObjToIntNull()",
                ["long?"] = $"{sourceExpr}.ObjToLongNull()",
                ["global::System.Int64?"] = $"{sourceExpr}.ObjToLongNull()",
                ["double?"] = $"{sourceExpr}.ObjToDoubleNull()",
                ["global::System.Double?"] = $"{sourceExpr}.ObjToDoubleNull()",
                ["decimal?"] = $"{sourceExpr}.ObjToDecimalNull()",
                ["global::System.Decimal?"] = $"{sourceExpr}.ObjToDecimalNull()",
                ["DateTime?"] = $"{sourceExpr}.ObjToDateNull()",
