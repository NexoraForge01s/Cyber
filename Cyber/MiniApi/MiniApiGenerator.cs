            if (IsSimpleTypeString(returnTypeName))
            {
                sb.AppendLine("              ctx.Response.ContentType = \"text/plain; charset=utf-8\";");
                sb.AppendLine($"              await ctx.Response.WriteAsync({dataExpr}?.ToString() ?? \"\");");
                return;
            }

            // 其它所有类型（实体/复杂类型）：统一 JSON 序列化
            var jsonTypeInfoName = MiniApiGenerationStatic.GetJsonTypeInfoPropertyName(returnTypeName);
            sb.AppendLine("              ctx.Response.ContentType = \"application/json\";");
            sb.AppendLine($"              await System.Text.Json.JsonSerializer.SerializeAsync(ctx.Response.Body, {dataExpr}, JsonTypeInfos.{jsonTypeInfoName});");
        }

