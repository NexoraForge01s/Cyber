            }

            // IFormFileCollection 多文件（按顺序拼接为流）
            if (returnTypeName == "Microsoft.AspNetCore.Http.IFormFileCollection" ||
                returnTypeName == "global::Microsoft.AspNetCore.Http.IFormFileCollection")
            {
                sb.AppendLine($"              if ({dataExpr} != null && {dataExpr}.Count > 0)");
                sb.AppendLine("               {");
