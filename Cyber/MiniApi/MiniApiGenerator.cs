        /// 生成类级别的端点映射（引用静态 handler 方法）
        /// </summary>
        private static void GenerateClassEndpointMappings(StringBuilder sb, MiniApiClassInfo classInfo)
        {
            var groupVar = $"__{classInfo.ClassName}Group";

            bool hasActionPlaceholder = classInfo.RoutePrefix.Contains("[action]");
            string baseRoutePrefix = classInfo.RoutePrefix;

            sb.AppendLine();
            sb.AppendLine($"            // {classInfo.ClassName} 端点");

            if (hasActionPlaceholder)
            {
                foreach (var method in classInfo.Methods)
                {
                    var methodRoutePrefix = baseRoutePrefix.Replace("[action]", method.MethodName);
                    var methodTemplate = method.RouteTemplate;
                    var inferredTemplate = method.MethodName;
                    if (methodTemplate == inferredTemplate)
                        methodTemplate = "";

                    var fullRoute = $"/{methodRoutePrefix}";
                    if (!string.IsNullOrEmpty(methodTemplate))
                        fullRoute += $"/{methodTemplate}";

                    GenerateMethodEndpointMapping(sb, classInfo, method, fullRoute, null);
                }
            }
            else
            {
                sb.Append($"            var {groupVar} = app.MapGroup(\"/{classInfo.RoutePrefix}\")");
                sb.Append($".WithTags(\"{classInfo.Tag}\")");

                foreach (var filter in classInfo.ClassFilters)
                {
                    sb.AppendLine();
                    sb.Append($"                .AddEndpointFilter<{filter.FilterTypeName}>()");
                }

                sb.AppendLine(";");

                foreach (var method in classInfo.Methods)
                {
                    GenerateMethodEndpointMapping(sb, classInfo, method, null, groupVar);
                }
            }
        }

        /// <summary>
        /// 生成单个方法的端点映射（引用静态 handler 方法）
        /// </summary>
        private static void GenerateMethodEndpointMapping(StringBuilder sb, MiniApiClassInfo classInfo,
            MiniApiMethodInfo method, string? fullRoute, string? groupVar)
        {
            var httpMethodCapitalized = method.HttpMethod.Substring(0, 1).ToUpperInvariant() + method.HttpMethod.Substring(1).ToLowerInvariant();
            var handlerMethodName = GetHandlerMethodName(classInfo.ClassName, method.MethodName, method.HttpMethod, method);
            var route = method.RouteTemplate;
            var routeStr = string.IsNullOrEmpty(route) ? "" : $"/{route}";
            var httpMethodUpper = method.HttpMethod.ToUpperInvariant();

            sb.AppendLine();

            // 使用 MapMethods 底层 API（零反射，生产级 AOT 首选）
            if (groupVar != null)
                sb.AppendLine($"            {groupVar}.MapMethods(\"{routeStr}\", new string[] {{ \"{httpMethodUpper}\" }}, __{handlerMethodName})");
            else
                sb.AppendLine($"            app.MapMethods(\"{fullRoute}\", new string[] {{ \"{httpMethodUpper}\" }}, __{handlerMethodName})");


            // 类级别过滤器（只在非 group 模式下添加）
            if (groupVar == null)
            {
                foreach (var filter in classInfo.ClassFilters)
                {
                    sb.AppendLine($"                .AddEndpointFilter<{filter.FilterTypeName}>()");
                }
            }

            // 方法级别过滤器
            foreach (var filter in method.MethodFilters)
            {
                sb.AppendLine($"                .AddEndpointFilter<{filter.FilterTypeName}>()");
            }

            if (groupVar != null)
                sb.AppendLine($"                .WithName(\"{classInfo.ClassName}_{method.MethodName}_{method.HttpMethod}{MiniApiGenerationStatic.GetMethodSignature(method)}\");");
            else
            {
                sb.AppendLine($"                .WithTags(\"{classInfo.Tag}\")");
                sb.AppendLine($"                .WithName(\"{classInfo.ClassName}_{method.MethodName}_{method.HttpMethod}{MiniApiGenerationStatic.GetMethodSignature(method)}\");");
            }
        }

