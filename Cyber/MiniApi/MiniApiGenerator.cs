        private static List<MiniApiMethodInfo> ExtractMethodInfo(IMethodSymbol method, INamedTypeSymbol classSymbol, string classRoutePrefix, Dictionary<string, string> validatorTypes)
        {
            // 查找所有 HTTP 方法特性（HttpGet, HttpPost, HttpPut, HttpDelete 等）
            var httpAttributes = new List<(string Method, string? Template)>();
            foreach (var attr in method.GetAttributes())
            {
                var attrName = attr.AttributeClass?.Name ?? "";
                var fullAttrName = attr.AttributeClass?.ToDisplayString() ?? "";

                // 检查是否是 HTTP 方法特性
                string? httpMethod = null;
                if (attrName == "HttpGetAttribute" || attrName == "HttpGet") httpMethod = "GET";
                else if (attrName == "HttpPostAttribute" || attrName == "HttpPost") httpMethod = "POST";
                else if (attrName == "HttpPutAttribute" || attrName == "HttpPut") httpMethod = "PUT";
                else if (attrName == "HttpDeleteAttribute" || attrName == "HttpDelete") httpMethod = "DELETE";
                else if (attrName == "HttpPatchAttribute" || attrName == "HttpPatch") httpMethod = "PATCH";
                else if (attrName == "HttpHeadAttribute" || attrName == "HttpHead") httpMethod = "HEAD";
                else if (attrName == "HttpOptionsAttribute" || attrName == "HttpOptions") httpMethod = "OPTIONS";

                // 也支持全名形式
                if (httpMethod == null)
                {
                    if (fullAttrName.StartsWith("Microsoft.AspNetCore.Mvc.HttpGet")) httpMethod = "GET";
                    else if (fullAttrName.StartsWith("Microsoft.AspNetCore.Mvc.HttpPost")) httpMethod = "POST";
                    else if (fullAttrName.StartsWith("Microsoft.AspNetCore.Mvc.HttpPut")) httpMethod = "PUT";
                    else if (fullAttrName.StartsWith("Microsoft.AspNetCore.Mvc.HttpDelete")) httpMethod = "DELETE";
                    else if (fullAttrName.StartsWith("Microsoft.AspNetCore.Mvc.HttpPatch")) httpMethod = "PATCH";
                    else if (fullAttrName.StartsWith("Microsoft.AspNetCore.Mvc.HttpHead")) httpMethod = "HEAD";
                    else if (fullAttrName.StartsWith("Microsoft.AspNetCore.Mvc.HttpOptions")) httpMethod = "OPTIONS";
                }

                if (httpMethod != null)
                {
                    // 读取路由模板（如果有）
                    string? template = null;
                    if (attr.ConstructorArguments.Length > 0 &&
                        attr.ConstructorArguments[0].Value is string t)
                    {
                        template = t;
                    }
                    httpAttributes.Add((httpMethod, template));
                }
            }

            // 如果没有 HTTP 特性，使用推断的方法
            if (httpAttributes.Count == 0)
            {
                var inferredMethod = InferHttpMethod(method.Name);
                var inferredTemplate = InferRouteTemplate(method.Name, method.Parameters);
                httpAttributes.Add((inferredMethod, inferredTemplate));
            }

            // 构建基础参数信息（所有 HTTP 方法共享）
            var parameters = new List<MiniApiParameterInfo>();
            bool noResultModel = method.GetAttributes().Any(a =>
                a.AttributeClass?.ToDisplayString() == "Cyber.NoResultModelAttribute" ||
                a.AttributeClass?.ToDisplayString() == "Cyber.NoResultModel");

            if (!noResultModel)
            {
                noResultModel = classSymbol.GetAttributes().Any(a =>
                    a.AttributeClass?.ToDisplayString() == "Cyber.NoResultModelAttribute" ||
                    a.AttributeClass?.ToDisplayString() == "Cyber.NoResultModel");
            }

            var methodFilters = ExtractMethodFilters(method);

            // 检查方法是否标记了 IgnoreRepeatedRequest 特性
            var methodIgnoreRepeatedRequest = method.GetAttributes().Any(a =>
                a.AttributeClass?.ToDisplayString() == "Cyber.IgnoreRepeatedRequestAttribute" ||
                a.AttributeClass?.ToDisplayString() == "Cyber.IgnoreRepeatedRequest");

            // 检查方法是否标记了 AllowAnonymous 特性（JWT 鉴权忽略）
            var methodAllowAnonymous = method.GetAttributes().Any(a =>
                a.AttributeClass?.ToDisplayString() == "Microsoft.AspNetCore.Authorization.AllowAnonymousAttribute" ||
                a.AttributeClass?.ToDisplayString() == "Cyber.AllowAnonymousAttribute" ||
                a.AttributeClass?.ToDisplayString() == "Cyber.AllowAnonymous" ||
                a.AttributeClass?.Name == "AllowAnonymousAttribute" ||
                a.AttributeClass?.Name == "AllowAnonymous");

            foreach (var param in method.Parameters)
            {
                var paramTypeFullName = param.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                var isSimpleType = IsSimpleType(param.Type);
                var isFileType = IsFileType(param.Type);

                // 提取实体类型的属性（用于 GET 请求从查询字符串组装对象）
                var entityProperties = isSimpleType || isFileType ? new List<PropertyInfo>() : ExtractEntityProperties(param.Type);

                var paramInfo = new MiniApiParameterInfo
                {
                    Name = param.Name,
                    Type = paramTypeFullName,
                    IsSimpleType = isSimpleType,
                    IsFileType = isFileType,
                    HasFromRoute = param.GetAttributes().Any(a =>
                        a.AttributeClass?.ToDisplayString() == "Cyber.FromRouteAttribute" ||
                        a.AttributeClass?.ToDisplayString() == "Cyber.FromRoute" ||
                        a.AttributeClass?.Name == "FromRouteAttribute" ||
                        a.AttributeClass?.Name == "FromRoute"),
                    HasFromQuery = param.GetAttributes().Any(a =>
                        a.AttributeClass?.ToDisplayString() == "Cyber.FromQueryAttribute" ||
                        a.AttributeClass?.ToDisplayString() == "Cyber.FromQuery" ||
                        a.AttributeClass?.Name == "FromQueryAttribute" ||
                        a.AttributeClass?.Name == "FromQuery"),
                    HasFromBody = param.GetAttributes().Any(a =>
                        a.AttributeClass?.ToDisplayString() == "Cyber.FromBodyAttribute" ||
                        a.AttributeClass?.ToDisplayString() == "Cyber.FromBody" ||
                        a.AttributeClass?.Name == "FromBodyAttribute" ||
                        a.AttributeClass?.Name == "FromBody"),
                    HasFromForm = param.GetAttributes().Any(a =>
                        a.AttributeClass?.ToDisplayString() == "Cyber.FromFormAttribute" ||
                        a.AttributeClass?.ToDisplayString() == "Cyber.FromForm" ||
                        a.AttributeClass?.Name == "FromFormAttribute" ||
                        a.AttributeClass?.Name == "FromForm"),
                    IsOptional = param.IsOptional,
                    IsParams = param.IsParams,
                    // 检查是否存在对应的 Validator
                    HasValidator = validatorTypes.TryGetValue(paramTypeFullName, out var validatorTypeName),
                    ValidatorTypeName = validatorTypes.TryGetValue(paramTypeFullName, out var vt) ? vt : "",
                    Properties = entityProperties
                };

                // 暂时先添加，后面会根据每个路由模板调整
                parameters.Add(paramInfo);
            }

            // 分析返回类型
            var returnType = method.ReturnType;
            var isAsync = returnType.Name == "Task" ||
                          returnType.ToDisplayString().StartsWith("System.Threading.Tasks.Task") ||
                          returnType.ToDisplayString().StartsWith("System.Threading.Tasks.ValueTask");

            string actualReturnType;
            bool isVoid = false;

            if (isAsync)
            {
                if (returnType is INamedTypeSymbol namedType && namedType.TypeArguments.Length > 0)
                {
                    actualReturnType = namedType.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                }
                else
                {
                    isVoid = true;
                    actualReturnType = "void";
                }
            }
            else
            {
                if (returnType.SpecialType == SpecialType.System_Void)
                {
                    isVoid = true;
                    actualReturnType = "void";
                }
                else
                {
                    actualReturnType = returnType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                }
            }

            // 为每个 HTTP 方法生成一个 MiniApiMethodInfo
            var results = new List<MiniApiMethodInfo>();
            foreach (var (httpMethod, template) in httpAttributes)
            {
                var routeTemplate = template ?? InferRouteTemplate(method.Name, method.Parameters);

                // 处理 [action] 占位符
                if (routeTemplate.Contains("[action]"))
                {
                    routeTemplate = routeTemplate.Replace("[action]", method.Name);
                }

                // 根据路由模板和 HTTP 方法调整参数的 FromRoute/FromQuery/FromBody/FromForm
                // 默认规则（无显式特性时）：
                //   - 文件类型 (IFormFile) -> FromForm
                //   - 简单类型：
                //       * 出现在路由占位符中 -> FromRoute
                //       * GET -> FromQuery (query string)
                //       * 其它 (POST/PUT/DELETE/PATCH) -> FromForm
                //   - 复杂/实体类型 -> FromBody (raw json)
                var adjustedParams = new List<MiniApiParameterInfo>();
                foreach (var p in parameters)
                {
                    var adjusted = new MiniApiParameterInfo
                    {
                        Name = p.Name,
                        Type = p.Type,
                        IsSimpleType = p.IsSimpleType,
                        IsFileType = p.IsFileType,
                        HasFromRoute = p.HasFromRoute,
                        HasFromQuery = p.HasFromQuery,
                        HasFromBody = p.HasFromBody,
                        HasFromForm = p.HasFromForm,
                        IsOptional = p.IsOptional,
                        IsParams = p.IsParams,
                        HasValidator = p.HasValidator,
                        ValidatorTypeName = p.ValidatorTypeName,
                        Properties = p.Properties
                    };

                    // 显式特性优先
                    if (!adjusted.HasFromRoute && !adjusted.HasFromQuery && !adjusted.HasFromBody && !adjusted.HasFromForm)
                    {
                        // 文件类型默认 form
                        if (adjusted.IsFileType)
                        {
                            adjusted.HasFromForm = true;
                        }
                        else if (adjusted.IsSimpleType)
                        {
                            if (routeTemplate.Contains($"{{{p.Name}}}") || routeTemplate.Contains($"{{{p.Name}:"))
                            {
                                adjusted.HasFromRoute = true;
                            }
                            else if (string.Equals(httpMethod, "GET", StringComparison.OrdinalIgnoreCase) ||
                                     string.Equals(httpMethod, "HEAD", StringComparison.OrdinalIgnoreCase) ||
                                     string.Equals(httpMethod, "DELETE", StringComparison.OrdinalIgnoreCase))
                            {
                                // GET/HEAD/DELETE：简单类型走 query string
                                adjusted.HasFromQuery = true;
                            }
                            else
                            {
                                // POST/PUT/PATCH 等：简单类型走 form
                                adjusted.HasFromForm = true;
                            }
                        }
                        else
                        {
                            // 实体类型处理
                            if (string.Equals(httpMethod, "GET", StringComparison.OrdinalIgnoreCase) ||
                                string.Equals(httpMethod, "HEAD", StringComparison.OrdinalIgnoreCase) ||
                                string.Equals(httpMethod, "DELETE", StringComparison.OrdinalIgnoreCase))
                            {
                                // GET/HEAD/DELETE：实体类型从查询字符串组装
                                adjusted.HasFromQuery = true;
                            }
                            else
                            {
                                // POST/PUT/PATCH 等：实体类型走 body (raw json)
                                adjusted.HasFromBody = true;
                            }
                        }
                    }

                    adjustedParams.Add(adjusted);
                }

                results.Add(new MiniApiMethodInfo
                {
                    MethodName = method.Name,
                    HttpMethod = httpMethod,
                    RouteTemplate = routeTemplate,
                    ReturnType = returnType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                    ActualReturnType = actualReturnType,
                    IsAsync = isAsync,
                    IsVoid = isVoid,
                    Parameters = adjustedParams,
                    MethodFilters = methodFilters,
                    NoResultModel = noResultModel,
                    IgnoreRepeatedRequest = methodIgnoreRepeatedRequest,
                    AllowAnonymous = methodAllowAnonymous
                });
            }

            return results;
        }

        private static string InferHttpMethod(string methodName)
        {
            var getPrefixes = new[] { "Get", "Find", "Query", "Search", "List", "Fetch", "Read" };
            var postPrefixes = new[] { "Post", "Add", "Create", "Insert", "New", "Save" };
            var putPrefixes = new[] { "Put", "Update", "Edit", "Modify", "Change" };
            var deletePrefixes = new[] { "Delete", "Remove", "Del" };
            var patchPrefixes = new[] { "Patch" };

            foreach (var prefix in getPrefixes)
                if (methodName.StartsWith(prefix, StringComparison.OrdinalIgnoreCase)) return "GET";
            foreach (var prefix in postPrefixes)
                if (methodName.StartsWith(prefix, StringComparison.OrdinalIgnoreCase)) return "POST";
            foreach (var prefix in putPrefixes)
                if (methodName.StartsWith(prefix, StringComparison.OrdinalIgnoreCase)) return "PUT";
            foreach (var prefix in deletePrefixes)
                if (methodName.StartsWith(prefix, StringComparison.OrdinalIgnoreCase)) return "DELETE";
            foreach (var prefix in patchPrefixes)
                if (methodName.StartsWith(prefix, StringComparison.OrdinalIgnoreCase)) return "PATCH";

            return "POST";
        }

        private static string InferRouteTemplate(string methodName, ImmutableArray<IParameterSymbol> parameters)
        {
            // 不再自动添加 {param} 到路由中。
            // 路径参数必须由用户显式通过 [HttpGet("by-id/{id}")] 等路由模板指定。
            // 未指定模板时直接使用方法名作为路由，参数绑定按默认规则：
            //   - GET + 简单类型 -> query string
            //   - 非 GET + 简单类型 -> form
            //   - 实体 -> body
            //   - 文件类型 (IFormFile) -> form file
            if (string.IsNullOrEmpty(methodName))
                return "";

            return methodName;
        }

        private static bool IsSimpleType(ITypeSymbol type)
        {
            var typeName = type.SpecialType;
            return typeName == SpecialType.System_String ||
                   typeName == SpecialType.System_Int32 ||
                   typeName == SpecialType.System_Int64 ||
                   typeName == SpecialType.System_Decimal ||
                   typeName == SpecialType.System_Double ||
                   typeName == SpecialType.System_Single ||
                   typeName == SpecialType.System_Boolean ||
                   typeName == SpecialType.System_DateTime ||
                   typeName == SpecialType.System_Byte ||
                   typeName == SpecialType.System_SByte ||
                   typeName == SpecialType.System_Int16 ||
                   typeName == SpecialType.System_UInt16 ||
                   typeName == SpecialType.System_UInt32 ||
                   typeName == SpecialType.System_UInt64 ||
                   type.TypeKind == TypeKind.Enum ||
                   type.ToDisplayString() == "System.Guid" ||
                   type.ToDisplayString() == "global::System.Guid" ||
                   type.ToDisplayString() == "Guid";
        }

        /// <summary>
        /// 判断类型是否为上传文件类型（IFormFile / IFormFileCollection）。
        /// </summary>
        private static bool IsFileType(ITypeSymbol type)
        {
            var fullName = type.ToDisplayString();
            return fullName == "Microsoft.AspNetCore.Http.IFormFile" ||
                   fullName == "global::Microsoft.AspNetCore.Http.IFormFile" ||
                   fullName == "Microsoft.AspNetCore.Http.IFormFileCollection" ||
                   fullName == "global::Microsoft.AspNetCore.Http.IFormFileCollection";
        }

        /// <summary>
        /// 提取实体类型的属性列表（用于从查询字符串组装实体对象）
        /// </summary>
        private static List<PropertyInfo> ExtractEntityProperties(ITypeSymbol type)
        {
            var properties = new List<PropertyInfo>();

            if (type is INamedTypeSymbol namedType)
            {
                foreach (var member in namedType.GetMembers())
                {
                    if (member is IPropertySymbol property && property.DeclaredAccessibility == Accessibility.Public)
                    {
                        // 只提取可读的属性
                        if (property.GetMethod != null)
                        {
                            var propType = property.Type;
                            var propTypeFullName = propType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                            var isSimpleType = IsSimpleType(propType);

                            // 检查是否为数组类型（List<T>、IEnumerable<T>、T[]、IList<T> 等）
                            var isArrayType = false;
                            var elementType = "";

                            // 检查数组类型 T[]
                            if (propType.TypeKind == TypeKind.Array && propType is IArrayTypeSymbol arrayType)
                            {
                                isArrayType = true;
                                elementType = arrayType.ElementType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                            }
                            // 检查泛型集合类型 List<T>、IEnumerable<T>、IList<T> 等
                            else if (propType is INamedTypeSymbol namedPropType && namedPropType.TypeArguments.Length > 0)
                            {
                                var typeDefName = namedPropType.OriginalDefinition?.ToDisplayString() ?? "";
                                if (typeDefName.StartsWith("System.Collections.Generic.List") ||
                                    typeDefName.StartsWith("System.Collections.Generic.IList") ||
                                    typeDefName.StartsWith("System.Collections.Generic.IEnumerable") ||
                                    typeDefName.StartsWith("System.Collections.Generic.ICollection") ||
                                    typeDefName.StartsWith("global::System.Collections.Generic.List") ||
                                    typeDefName.StartsWith("global::System.Collections.Generic.IList") ||
                                    typeDefName.StartsWith("global::System.Collections.Generic.IEnumerable") ||
                                    typeDefName.StartsWith("global::System.Collections.Generic.ICollection"))
                                {
                                    isArrayType = true;
                                    elementType = namedPropType.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                                }
                            }

                            properties.Add(new PropertyInfo
                            {
                                Name = property.Name,
                                Type = propTypeFullName,
                                IsSimpleType = isSimpleType,
                                IsArrayType = isArrayType,
                                ElementType = elementType
                            });
                        }
                    }
                }
            }

            return properties;
        }

        private static List<AutowiredMember> ExtractConstructorParameters(INamedTypeSymbol classSymbol)
        {
            var parameters = new List<AutowiredMember>();
            var constructor = classSymbol.Constructors.FirstOrDefault(c => c.DeclaredAccessibility == Accessibility.Public);
            if (constructor == null) return parameters;

            foreach (var param in constructor.Parameters)
            {
                parameters.Add(new AutowiredMember
                {
                    Name = param.Name,
                    TypeName = param.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                    Required = true
                });
            }
            return parameters;
        }

        /// <summary>
        /// 获取响应类型的名称
        /// </summary>
        internal static string GetResponseTypeName(string className, string methodName, string httpMethod, MiniApiMethodInfo? method = null)
        {
            // 加入参数签名以区分同名重载方法
            var signature = method != null ? GetMethodSignature(method) : "";
            return $"{className}_{methodName}_{httpMethod}{signature}_Response";
        }
        /// <summary>
        /// 获取方法参数签名（用于区分重载方法）
        /// </summary>
        internal static string GetMethodSignature(MiniApiMethodInfo method)
        {
            if (method.Parameters.Count == 0) return "";

            // 使用参数类型的简化名称拼接作为签名
            var paramTypes = method.Parameters.Select(p => GetSimpleTypeName(p.Type));
            var signature = "_" + string.Join("_", paramTypes);
            return signature;
        }
        /// <summary>
        /// 获取类型的简化名称（用于生成签名）
        /// </summary>
        internal static string GetSimpleTypeName(string fullType)
        {
            // 去除 global:: 前缀
            if (fullType.StartsWith("global::"))
                fullType = fullType.Substring(8);

            // 先处理泛型参数（泛型参数可能包含命名空间）
            var genericIndex = fullType.IndexOf('<');
            if (genericIndex >= 0)
            {
                var baseName = fullType.Substring(0, genericIndex);
                // 去除基类型的命名空间
                var lastDot = baseName.LastIndexOf('.');
                if (lastDot >= 0)
                    baseName = baseName.Substring(lastDot + 1);

                // 提取泛型参数并简化
                var genericParams = ExtractGenericParameters(fullType);
                var simplifiedParams = genericParams
                    .Select(p => GetSimpleTypeName(p.Trim()))
                    .ToList();
                return $"{baseName}Of{string.Join("And", simplifiedParams)}";
            }

            // 去除命名空间，只保留类型名
            var lastDot2 = fullType.LastIndexOf('.');
            if (lastDot2 >= 0)
                fullType = fullType.Substring(lastDot2 + 1);

            return fullType;
        }
        /// <summary>
        /// 提取泛型参数（正确处理嵌套泛型）
        /// </summary>
        private static List<string> ExtractGenericParameters(string typeWithGenerics)
        {
            var result = new List<string>();
            var start = typeWithGenerics.IndexOf('<');
            if (start < 0) return result;

            var depth = 0;
            var currentParam = new System.Text.StringBuilder();
            for (int i = start + 1; i < typeWithGenerics.Length; i++)
            {
                var c = typeWithGenerics[i];
                if (c == '<')
                {
                    depth++;
                    currentParam.Append(c);
                }
                else if (c == '>')
                {
                    if (depth > 0)
                    {
                        depth--;
                        currentParam.Append(c);
                    }
                    else
                    {
                        // 结束最后一个参数
                        if (currentParam.Length > 0)
                            result.Add(currentParam.ToString());
                        break;
                    }
                }
                else if (c == ',' && depth == 0)
                {
                    result.Add(currentParam.ToString());
                    currentParam.Clear();
                }
                else
                {
                    currentParam.Append(c);
                }
            }
            return result;
        }

        /// <summary>
        /// 获取类型在 JsonTypeInfos 中的属性名称
        /// 例如：global::Test.UserDto -> UserDto
        /// 例如：Test.UserDto -> UserDto
        /// 例如：global::System.Collections.Generic.List<global::Test.SMSTemplate> -> IEnumerable_SMSTemplate
        /// </summary>
        internal static string GetJsonTypeInfoPropertyName(string type)
        {
            // 处理 global:: 前缀
            var typeName = type.Replace("global::", "");

            // 处理泛型类型
            if (typeName.Contains("<"))
            {
                // 提取基础类型名（去掉 <...> 部分）
                var genericIndex = typeName.IndexOf('<');
                var baseName = typeName.Substring(0, genericIndex);

                // 提取基础类型的 SimpleName（去掉命名空间）
                var lastDot = baseName.LastIndexOf('.');
                if (lastDot >= 0)
                    baseName = baseName.Substring(lastDot + 1);

                // 如果基础类型是 List，改为使用 IEnumerable（统一集合类型处理）
                if (baseName == "List"|| baseName == "IList")
                    baseName = "IEnumerable";

                // 提取泛型参数
                var genericParamsStr = typeName.Substring(genericIndex + 1, typeName.Length - genericIndex - 2);
                var genericParams = genericParamsStr.Split(',').Select(p => p.Trim()).ToList();

                // 对每个泛型参数提取 SimpleName
                var simplifiedParams = genericParams.Select(p => GetJsonTypeInfoPropertyName(p)).ToList();

                // 组合：BaseName_Param1_Param2...
                return $"{baseName}_{string.Join("_", simplifiedParams)}";
            }

            // 非泛型：去掉命名空间，只保留类型名
            if (typeName.Contains("."))
            {
                typeName = typeName.Substring(typeName.LastIndexOf('.') + 1);
            }

            return typeName;
        }

        /// <summary>
        /// 获取用于 JsonTypeInfo/ReadFromJsonAsync 的类型名称
        /// 将 List/IList 转换为 IEnumerable（统一使用 IEnumerable 转换器）
        /// 例如：List<Test.UserDto> -> IEnumerable<Test.UserDto>
        /// 例如：IList<Test.UserDto> -> IEnumerable<Test.UserDto>
        /// 例如：Test.UserDto -> Test.UserDto
        /// </summary>
        internal static string GetJsonSerializationType(string type)
        {
            // 处理 global:: 前缀
            var typeName = type.Replace("global::", "");

            // 处理泛型类型
            if (typeName.Contains("<"))
            {
                var genericIndex = typeName.IndexOf('<');
                var baseName = typeName.Substring(0, genericIndex);

                // 如果是 List 或 IList，转换为 IEnumerable
                if (baseName == "List" || baseName == "System.Collections.Generic.List" ||
                    baseName == "IList" || baseName == "System.Collections.Generic.IList")
                {
                    var genericParam = typeName.Substring(genericIndex + 1, typeName.Length - genericIndex - 2);
                    return $"System.Collections.Generic.IEnumerable<{genericParam}>";
                }
            }

            // 其他类型保持不变
            return type;
        }

