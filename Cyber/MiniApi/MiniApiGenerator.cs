        internal static MiniApiClassInfo? GetMiniApiClassInfo(GeneratorSyntaxContext context)
        {
            var classDecl = (ClassDeclarationSyntax)context.Node;
            var classSymbol = context.SemanticModel.GetDeclaredSymbol(classDecl);
            if (classSymbol == null) return null;

            if (classSymbol.IsAbstract || classSymbol.DeclaredAccessibility != Accessibility.Public)
                return null;

            // 检查类是否实现了 IMiniApiController 接口
            bool implementsMiniApi = false;
            foreach (var iface in classSymbol.AllInterfaces)
            {
                if (iface.ToDisplayString() == "Cyber.IMiniApiController" ||
                    iface.Name == "IMiniApiController")
                {
                    implementsMiniApi = true;
                    break;
                }
            }

            if (!implementsMiniApi) return null;

            // 从 [Route] 特性读取路由前缀
            string? routePrefix = null;
            foreach (var attr in classSymbol.GetAttributes())
            {
                var attrName = attr.AttributeClass?.ToDisplayString();
                if (attrName == "Microsoft.AspNetCore.Mvc.RouteAttribute" ||
                    attrName == "Route" ||
                    attrName == "RouteAttribute")
                {
                    if (attr.ConstructorArguments.Length > 0 &&
                        attr.ConstructorArguments[0].Value is string routeTemplate)
                    {
                        routePrefix = routeTemplate;
                        // 替换 [controller] 为实际控制器名（去掉后缀）
                        if (routePrefix.Contains("[controller]"))
                        {
                            var controllerName = InferRoutePrefix(classSymbol.Name);
                            routePrefix = routePrefix.Replace("[controller]", controllerName);
                        }
                    }
                    break;
                }
            }

            if (string.IsNullOrEmpty(routePrefix))
                routePrefix = InferRoutePrefix(classSymbol.Name);

            var tag = InferRoutePrefix(classSymbol.Name);

            // 存储 routePrefix 用于方法级别的 [action] 替换
            string classRoutePrefix = routePrefix!;

            var classFilters = ExtractFilters(classSymbol);
            var classIgnoreRepeatedRequest = classSymbol.GetAttributes().Any(a =>
                a.AttributeClass?.ToDisplayString() == "Cyber.IgnoreRepeatedRequestAttribute" ||
                a.AttributeClass?.ToDisplayString() == "Cyber.IgnoreRepeatedRequest");

            // 先获取 ValidatorTypes，以便在提取方法信息时使用
            var validatorTypes = FindValidatorTypes(context.SemanticModel.Compilation, classSymbol.ContainingAssembly);

            var methods = new List<MiniApiMethodInfo>();
            foreach (var member in classSymbol.GetMembers())
            {
                if (member is IMethodSymbol method && method.DeclaredAccessibility == Accessibility.Public
                    && method.MethodKind == MethodKind.Ordinary
                    && !method.IsStatic)
                {
                    var methodInfos = ExtractMethodInfo(method, classSymbol, classRoutePrefix, validatorTypes);
                    methods.AddRange(methodInfos);
                }
            }

            return new MiniApiClassInfo
            {
                ClassName = classSymbol.Name,
                FullClassName = classSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                Namespace = classSymbol.ContainingNamespace.ToDisplayString(),
                RoutePrefix = routePrefix!,
                Tag = tag!,
                ClassFilters = classFilters,
                Methods = methods,
                ConstructorParameters = ExtractConstructorParameters(classSymbol),
                ValidatorTypes = validatorTypes,
                IgnoreRepeatedRequest = classIgnoreRepeatedRequest
            };
        }

        /// <summary>
        /// 查找程序集中所有继承自 AbstractValidator&lt;T&gt; 的 Validator 类
        /// </summary>
        private static Dictionary<string, string> FindValidatorTypes(Compilation compilation, IAssemblySymbol assembly)
        {
            var validators = new Dictionary<string, string>();

            // 遍历程序集中的所有类型
            foreach (var namespaceSymbol in assembly.GlobalNamespace.GetNamespaceMembers())
            {
                FindValidatorTypesInNamespace(namespaceSymbol, validators);
            }

            return validators;
        }

        /// <summary>
        /// 递归查找命名空间中的 Validator 类型
        /// </summary>
        private static void FindValidatorTypesInNamespace(INamespaceSymbol namespaceSymbol, Dictionary<string, string> validators)
        {
            // 查找命名空间中的所有类型
            foreach (var typeMember in namespaceSymbol.GetTypeMembers())
            {
                // 检查是否继承自 AbstractValidator<T>
                if (InheritsFromAbstractValidator(typeMember))
                {
                    // 获取泛型参数 T 的类型
                    var baseType = typeMember.BaseType;
                    while (baseType != null)
                    {
                        if (baseType.OriginalDefinition.Name == "AbstractValidator" &&
                            baseType is INamedTypeSymbol namedBase &&
                            namedBase.TypeArguments.Length > 0)
                        {
                            var validatedType = namedBase.TypeArguments[0];
                            var validatedTypeFullName = validatedType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                            var validatorTypeFullName = typeMember.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

                            validators[validatedTypeFullName] = validatorTypeFullName;
                            break;
                        }
                        baseType = baseType.BaseType;
                    }
                }
            }

            // 递归查找子命名空间
            foreach (var subNamespace in namespaceSymbol.GetNamespaceMembers())
            {
                FindValidatorTypesInNamespace(subNamespace, validators);
            }
        }

        /// <summary>
        /// 检查类型是否继承自 AbstractValidator&lt;T&gt;
        /// </summary>
        private static bool InheritsFromAbstractValidator(INamedTypeSymbol typeSymbol)
        {
            var baseType = typeSymbol.BaseType;
            while (baseType != null)
            {
                if (baseType.OriginalDefinition.Name == "AbstractValidator" ||
                    baseType.OriginalDefinition.ToDisplayString().Contains("AbstractValidator"))
                {
                    return true;
                }
                baseType = baseType.BaseType;
            }
            return false;
        }

        private static string InferRoutePrefix(string className)
        {
            var suffixes = new[] { "Service", "AppService", "AppServices", "Controller", "Api", "Endpoints" };
            foreach (var suffix in suffixes)
            {
                if (className.EndsWith(suffix) && className.Length > suffix.Length)
                {
                    className = className.Substring(0, className.Length - suffix.Length);
                    break;
                }
            }
            return className;
        }
