        /// <summary>
        /// [NoResultModel] 原始响应序列化：根据返回类型分派到不同输出通道。
        ///   - IFormFile           -> 文件下载（CopyToAsync）
        ///   - IFormFileCollection -> 拼接所有文件流
        ///   - byte[]              -> 二进制
        ///   - string              -> text/plain（避免 JSON 序列化 string 走不到 TypeInfoResolver）
        ///   - 其它简单类型         -> text/plain（ToString）
        ///   - 实体/复杂类型        -> JSON 序列化
        /// </summary>
        private static void GenerateRawResponseSerialization(StringBuilder sb, string returnTypeName, string dataExpr)
        {
