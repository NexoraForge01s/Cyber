        /// <summary>
        /// 从命令行参数中获取指定参数的值
        /// </summary>
        /// <param name=""args"">命令行参数数组</param>
        /// <param name=""paramName"">参数名，如 ""port""</param>
        /// <returns>如果找到参数值则返回参数值，否则返回null</returns>
        private static string GetParamValue(string[] args, string paramName)
        {
            if (args == null || args.Length == 0 || string.IsNullOrEmpty(paramName))
                return null;

            for (int i = 0; i < args.Length; i++)
            {
                var arg = args[i];
                if (arg != null)
                {
                    // 匹配 --paramName:值 或 --paramName=值 格式
                    if (arg.StartsWith(""--"" + paramName + "":"", StringComparison.OrdinalIgnoreCase))
                    {
                        return arg.Substring(3 + paramName.Length); // 移除 ""--paramName:"" 前缀
                    }
                    else if (arg.StartsWith(""--"" + paramName + ""="", StringComparison.OrdinalIgnoreCase))
                    {
                        return arg.Substring(3 + paramName.Length); // 移除 ""--paramName="" 前缀
                    }
                    // 匹配 --paramName 或 -p (单字符缩写) 后面跟空格分隔的值格式
                    else if (string.Equals(arg, ""--"" + paramName, StringComparison.OrdinalIgnoreCase))
                    {
                        // 检查下一个参数是否为值
                        if (i + 1 < args.Length)
                        {
                            return args[i + 1];
                        }
                    }
                    // 匹配简短参数格式，如 -p:值 或 -p=值
                    else if (arg.StartsWith(""-"", StringComparison.Ordinal) && !arg.StartsWith(""--"", StringComparison.Ordinal))
                    {
                        // 这里假设参数名的第一个字母作为简写，例如 ""port"" -> ""p""
                        if (arg.Length > 1 && char.ToLowerInvariant(arg[1]) == paramName[0])
                        {
                            // 检查是否是 -p:值 或 -p=值 格式
                            var colonIndex = arg.IndexOf(':');
                            var equalIndex = arg.IndexOf('=');
                            var separatorIndex = Math.Min(colonIndex >= 0 ? colonIndex : int.MaxValue,
                                                         equalIndex >= 0 ? equalIndex : int.MaxValue);

                            if (separatorIndex != int.MaxValue)
                            {
                                return arg.Substring(separatorIndex + 1);
                            }
                            // 检查 -p 后面跟空格分隔的值格式
                            else
                            {
                                // 检查下一个参数是否为值
                                if (i + 1 < args.Length)
                                {
                                    return args[i + 1];
                                }
                            }
                        }
                    }
                }
            }

            return null;
        }


        /// <summary>
        /// 从命令行参数中获取端口号
        /// 支持多种格式，如 --port:55421, --port=55421, --port 55421, -p 55421 等
        /// </summary>
        /// <param name=""args"">命令行参数数组</param>
        /// <returns>如果找到有效端口号则返回端口号，否则返回null</returns>
        private static int? GetPortFromArgs(string[] args)
        {
            var portStr = GetParamValue(args, ""port"");
            if (string.IsNullOrEmpty(portStr))
                return null;

            if (int.TryParse(portStr, out int port) && IsValidPort(port))
            {
                return port;
            }

            return null;
        }

        /// <summary>
        /// 验证端口号是否有效
        /// </summary>
        /// <param name=""port"">待验证的端口号</param>
        /// <returns>如果端口号在有效范围内则返回true，否则返回false</returns>
        private static bool IsValidPort(int port)
        {
            return port > 0 && port <= 65535;
        }

