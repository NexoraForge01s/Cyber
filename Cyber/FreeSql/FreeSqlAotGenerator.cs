using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;

namespace Cyber.AOT.FreeSql
{
    /// <summary>
    /// FreeSql AOT 兼容性源生成器
    /// 自动为带有 [Table] 或 [Column] 特性的实体类添加 DynamicDependency 构造函数
    /// 确保 AOT 发布后 FreeSql 能正常访问构造函数
    /// </summary>
    [Generator]
    public class FreeSqlAotGenerator : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            // 查找所有可能的 FreeSql 实体类
            var entityTypes = context.SyntaxProvider
                .CreateSyntaxProvider(
                    predicate: static (s, _) => IsPotentialEntityType(s),
                    transform: static (ctx, _) => GetEntityTypeInfo(ctx))
                .Where(static m => m is not null);

            context.RegisterImplementationSourceOutput(
                entityTypes.Collect(),
                static (spc, types) =>
                {
                    if (types.IsEmpty)
                        return;

                    var source = GenerateDynamicDependencyConstructors(types);
                    spc.AddSource("FreeSqlAotConstructors.g.cs", SourceText.From(source, Encoding.UTF8));
                });
        }

        /// <summary>
        /// 判断是否可能是 FreeSql 实体类型（类声明）
        /// </summary>
        private static bool IsPotentialEntityType(SyntaxNode node)
        {
            return node is ClassDeclarationSyntax;
        }

        /// <summary>
        /// 获取实体类型信息
        /// </summary>
        private static EntityTypeInfo? GetEntityTypeInfo(GeneratorSyntaxContext context)
        {
            var classDecl = (ClassDeclarationSyntax)context.Node;
            var symbol = context.SemanticModel.GetDeclaredSymbol(classDecl) as INamedTypeSymbol;
            
            if (symbol == null)
                return null;

            // 排除抽象类
            if (symbol.IsAbstract)
                return null;

            // 排除静态类
            if (symbol.IsStatic)
                return null;

            // 排除非 public 类
            if (symbol.DeclaredAccessibility != Accessibility.Public)
                return null;

            // 检查是否有 [Table] 特性
            var hasTableAttribute = symbol.GetAttributes().Any(a =>
                a.AttributeClass?.Name == "Table" ||
                a.AttributeClass?.ToDisplayString().Contains("TableAttribute") == true);

            // 检查是否有字段带有 [Column] 特性
            var hasColumnAttribute = symbol.GetMembers()
                .OfType<IPropertySymbol>()
                .Any(p => p.GetAttributes().Any(a =>
                    a.AttributeClass?.Name == "Column" ||
                    a.AttributeClass?.ToDisplayString().Contains("ColumnAttribute") == true));

            // 如果既没有 Table 特性也没有 Column 特性，则跳过
            if (!hasTableAttribute && !hasColumnAttribute)
                return null;

            // 检查是否已有显式定义的构造函数（排除隐式无参构造函数）
            // 只有当类没有任何显式构造函数时才需要生成
            var hasExplicitConstructor = symbol.Constructors
                .Any(c => !c.IsImplicitlyDeclared);

            if (hasExplicitConstructor)
                return null; // 已有显式构造函数，不需要生成

            return new EntityTypeInfo
            {
                TypeName = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                SimpleName = symbol.Name,
                Namespace = symbol.ContainingNamespace?.ToDisplayString() ?? ""
            };
        }

        /// <summary>
        /// 生成 DynamicDependency 构造函数代码
        /// </summary>
        private static string GenerateDynamicDependencyConstructors(ImmutableArray<EntityTypeInfo?> types)
        {
            var sb = new StringBuilder();

            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#pragma warning disable");
            sb.AppendLine();
            sb.AppendLine("using System.Diagnostics.CodeAnalysis;");
            sb.AppendLine();
            sb.AppendLine("namespace Cyber.FreeSqlAot");
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary>");
            sb.AppendLine("    /// FreeSql AOT 兼容性扩展 - 自动生成的 DynamicDependency 构造函数");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine("    public static class FreeSqlAotConstructorExtensions");
            sb.AppendLine("    {");
            sb.AppendLine("        /// <summary>");
            sb.AppendLine("        /// 为 FreeSql 实体类注入 AOT 兼容的构造函数");
            sb.AppendLine("        /// 通过 partial class 扩展方式添加带 DynamicDependency 属性的构造函数");
            sb.AppendLine("        /// </summary>");

            // 生成每个实体类的 partial 扩展
            foreach (var type in types)
            {
                if (type == null)
                    continue;

                sb.AppendLine();
                sb.AppendLine($"        // {type.Value.SimpleName} 实体类扩展");
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");
            sb.AppendLine();

            // 为每个实体类生成 partial class 定义
            foreach (var type in types)
            {
                if (type == null)
                    continue;

                sb.AppendLine($"namespace {type.Value.Namespace}");
                sb.AppendLine("{");
                sb.AppendLine($"    /// <summary>");
                sb.AppendLine($"    /// FreeSql AOT 兼容性扩展 - {type.Value.SimpleName} 构造函数");
                sb.AppendLine($"    /// 自动添加 DynamicDependency 属性确保构造函数在 AOT 发布后可访问");
                sb.AppendLine($"    /// </summary>");
                sb.AppendLine($"    public partial class {type.Value.SimpleName}");
                sb.AppendLine($"    {{");
                sb.AppendLine($"        [DynamicDependency(DynamicallyAccessedMemberTypes.All, typeof({type.Value.SimpleName}))]");
                sb.AppendLine($"        public {type.Value.SimpleName}()");
                sb.AppendLine($"        {{");
                sb.AppendLine($"        }}");
                sb.AppendLine($"    }}");
                sb.AppendLine($"}}");
                sb.AppendLine();
            }

            return sb.ToString();
        }

        /// <summary>
        /// 实体类型信息
        /// </summary>
        private record struct EntityTypeInfo
        {
            public string TypeName { get; set; }
            public string SimpleName { get; set; }
            public string Namespace { get; set; }
        }
    }
}